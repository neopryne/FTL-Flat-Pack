-- enabled
function Cell:setEnabled(enabled)
    self._enabled = enabled
    if not enabled then
        self:setAlive(false)
        self:setNextAlive(false)
        if (self._particle ~= nil) then
            Brightness.destroy_particle(self._particle)
            self._particle = nil
        end
    else
        self._particle = Brightness.create_particle("particles/game_of_life/1", 1, 1, Hyperspace.Pointf(0,0), 0, 0, RENDER_LAYER)
        self._particle.persists = true
    end
end

