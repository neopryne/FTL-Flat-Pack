--- square grid, square cells.
---@param x number Non-negative
---@param y number Non-negative
---@param size number 
---@return table
function Cell.new(x, y, size, renderSpace)
    local self = setmetatable({}, Cell)
    local xOffset = (x - 1) * size
    local yOffset = (y - 1) * size

    self._boardPosition = {x=x, y=y}
    self._offset = {x=xOffset, y=yOffset}
    self._width = size
    self._height = size
    self._renderSpace = renderSpace

    self:setEnabled(true)
    self._alive     = false
    self._nextAlive = false

    return self
end